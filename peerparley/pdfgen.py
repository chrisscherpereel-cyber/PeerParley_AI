# 3. Instructor section summary PDF  (landscape, all data)
# --------------------------------------------------------------------------- #
def build_section_summary_pdf(teams: List[TeamResult], course: str = "",
                              eval_no: str = "") -> bytes:
    buf = io.BytesIO()
    pw, ph = landscape(letter)
    c = canvas.Canvas(buf, pagesize=landscape(letter))
    y = _header(c, "Instructor Section Summary", course or "", pw, ph)
    c.setFillColor(B.GREY); c.setFont("Helvetica", 9)
    c.drawString(MARGIN, y, f"{len(teams)} teams  ·  "
                 f"{sum(len(t.members) for t in teams)} students"
                 + (f"  ·  Eval {eval_no}" if eval_no else ""))
    y -= 22

    # column layout (inches from left margin)
    cols = [("Name", 0.0), ("TmPl", 3.2), ("Qty", 3.7), ("Qual", 4.2), ("Effect", 4.7),
            ("Pay", 5.4), ("Ratio", 5.9), ("A", 6.5), ("Q", 6.9), ("Resp.Pts", 7.3),
            ("Mult", 8.1), ("Grade Δ", 8.7), ("Perf", 9.4)]

    def col_header():
        c.setFont("Helvetica-Bold", 8); c.setFillColor(B.GREY)
        for label, dx in cols:
            c.drawString(MARGIN + dx * inch, yy[0], label)
        yy[0] -= 12
        c.setStrokeColor(B.GREY_LIGHT); c.setLineWidth(0.8)
        c.line(MARGIN, yy[0] + 4, pw - MARGIN, yy[0] + 4)

    yy = [y]
    for t in teams:
        if yy[0] < MARGIN + 1.2 * inch:
            _footer(c, page_w=pw); c.showPage(); yy[0] = ph - MARGIN
        c.setFillColor(B.NAVY); c.setFont("Helvetica-Bold", 11)
        c.drawString(MARGIN, yy[0], f"Team {t.team}")
        c.setFont("Helvetica", 8); c.setFillColor(B.GREY)
        c.drawRightString(pw - MARGIN, yy[0], f"Team score {t.team_score:g}")
        yy[0] -= 14
        col_header()
        for m in t.members:
            c.setFont("Helvetica", 8); c.setFillColor(B.NAVY)
            vals = [m.name[:30], m.team_player or "—", m.quantity or "—", m.quality or "—",
                    m.effect or "—", "" if _is_nan(m.pay_grade) else f"{m.pay_grade:.0%}",
                    f"{m.peer_ratio:g}", f"{m.A:g}", f"{m.Q:g}", str(m.response_points),
                    f"{m.multiplier:g}", "", m.performance[:9]]
            for (label, dx), v in zip(cols, vals):
                if label == "Grade Δ":
                    c.setFillColor(B.grade_color(m.signed_pct))
                    c.drawString(MARGIN + dx * inch, yy[0],
                                 f"{'+' if m.signed_pct >= 0 else ''}{m.signed_pct:g}%")
                    c.setFillColor(B.NAVY)
                else:
                    c.drawString(MARGIN + dx * inch, yy[0], v)
            yy[0] -= 12
            if yy[0] < MARGIN + 0.9 * inch:
                _footer(c, page_w=pw); c.showPage(); yy[0] = ph - MARGIN
        yy[0] -= 10

    if yy[0] < MARGIN + 1.6 * inch:
        _footer(c, page_w=pw); c.showPage(); yy[0] = ph - MARGIN
    c.setFillColor(B.NAVY); c.setFont("Helvetica-Bold", 9)
    c.drawString(MARGIN, yy[0], "What each column means"); yy[0] -= 13
    legend = [
        "TmPl / Qty / Qual / Effect = letter grades from the 4-statement rating matrix.",
        "Pay = average received allocation vs the team average.  Ratio = received vs fair share.",
        "A = evaluator agreement weight.  Q = support behind the ratings received (drives the multiplier).",
        "Resp.Pts = points earned for the QUALITY of the feedback this student wrote.",
        "Mult = final grade multiplier.  Grade Δ = signed adjustment vs the team score.",
        "Perf = performance from the forced ranking (High / Adequate / Low).",
    ]
    for ln in legend:
        c.setFont("Helvetica", 8); c.setFillColor(B.GREY)
        c.drawString(MARGIN, yy[0], "• " + ln); yy[0] -= 11

    # ---- confidential comments to the instructor ----
    conf_rows = [(t.team, m.name, [x for x in m.confidential_comments if x.strip()])
                 for t in teams for m in t.members
                 if any(x.strip() for x in m.confidential_comments)]
    if conf_rows:
        _footer(c, page_w=pw); c.showPage(); yy[0] = ph - MARGIN
        c.setFillColor(B.RED); c.setFont("Helvetica-Bold", 12)
        c.drawString(MARGIN, yy[0], "Confidential comments to the instructor")
        yy[0] -= 6
        c.setFont("Helvetica", 8); c.setFillColor(B.GREY)
        c.drawString(MARGIN, yy[0], "Not released to students.")
        yy[0] -= 8
        c.setStrokeColor(B.GREEN_LIGHT); c.setLineWidth(1.5)
        c.line(MARGIN, yy[0], pw - MARGIN, yy[0]); yy[0] -= 18
        for team, name, notes in conf_rows:
            if yy[0] < MARGIN + 1.0 * inch:
                _footer(c, page_w=pw); c.showPage(); yy[0] = ph - MARGIN
            c.setFillColor(B.NAVY); c.setFont("Helvetica-Bold", 9.5)
            c.drawString(MARGIN, yy[0], f"{name}  ·  Team {team}"); yy[0] -= 14
            for txt in notes:
                c.setFont("Helvetica", 9); c.setFillColor(B.NAVY)
                for line in simpleSplit("— " + txt, "Helvetica", 9, pw - 2 * MARGIN - 0.1 * inch):
                    if yy[0] < MARGIN + 0.7 * inch:
                        _footer(c, page_w=pw); c.showPage(); yy[0] = ph - MARGIN
                    c.drawString(MARGIN + 0.1 * inch, yy[0], line); yy[0] -= 12
                yy[0] -= 4
            yy[0] -= 6

    _footer(c, "Instructor section summary — confidential.", page_w=pw)
    c.showPage(); c.save()
    return buf.getvalue()


